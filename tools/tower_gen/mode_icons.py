def hexrgb(h: str) -> tuple[int, int, int]:
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def icon(mode: str) -> np.ndarray:
    """RGBA 16 x 16, 0..1."""
    art, palette = MAPS[mode]
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), mode
    out = np.zeros((16, 16, 4))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            rgb = OUTLINE if ch == "o" else hexrgb(palette[ch])
            out[y, x] = (*[c / 255 for c in rgb], 1.0)
    return out


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    out.mkdir(parents=True, exist_ok=True)
    sheet = Image.new("RGBA", (len(MODES) * 136 + 8, 144), (34, 30, 44, 255))
    for i, m in enumerate(MODES):
        im = Image.fromarray((icon(m) * 255).astype(np.uint8), "RGBA")
        im.save(out / f"{m}.png")
        sheet.alpha_composite(im.resize((128, 128), Image.NEAREST), (8 + i * 136, 8))
    sheet.save(out / "mode_icons_sheet.png")
    print("ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
