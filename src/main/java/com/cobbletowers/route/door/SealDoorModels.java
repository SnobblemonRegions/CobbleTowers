package com.cobbletowers.route.door;

import com.cobbletowers.route.RouteGraph;
import com.cobbletowers.route.RouteMap;
import eu.pb4.polymer.resourcepack.api.PolymerModelData;
import eu.pb4.polymer.resourcepack.api.PolymerResourcePackUtils;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import net.minecraft.core.component.DataComponents;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.component.CustomModelData;

/**
 * The Split Seal route door's models (P59), generated by {@code tools/gate_door/gen_seal_door.py}: one set of six parts per tower trim, in the Grand
 * door's order and model space ({@code assets/cobbletowers/models/gate_door/<trim>/}), and every route stop's icon cut into a left and right half
 * ({@code .../gate_door/icon/<stop>_<side>}), each half riding its leaf.
 */
public final class SealDoorModels {

    /** Keep in step with TRIM_IDS in the generator. */
    public static final List<String> TRIMS = List.of("neutral", "duskvale", "rootvale", "tideforge", "poke", "hollows_eve");
    static final String[] PARTS = {"frame", "frame_glow", "left", "left_glow", "right", "right_glow"};

    private SealDoorModels() {}

    /** The trim a tower's doors wear, by the tower id's path; a tower with no trim of its own wears Neutral's. */
    public static String trimOf(ResourceLocation towerId) {
        return switch (towerId.getPath()) {
            case "duskvale", "rootvale", "tideforge" -> towerId.getPath();
            case "test" -> "poke";
            case "halloween" -> "hollows_eve";
            default -> "neutral";
        };
    }

    /** The stop whose icon a lane of {@code kind} shows on its door. A kind with no stop of its own shows the battle icon. */
    public static RouteMap.Stop stopOf(RouteGraph.Kind kind) {
        if (kind == RouteGraph.Kind.GAMBLER) return RouteMap.Stop.MERCHANT;
        try {
            return RouteMap.Stop.valueOf(kind.name());
        } catch (IllegalArgumentException none) {
            return RouteMap.Stop.BATTLE;
        }
    }

    /** The side a part swings on: the frame and its glow never move (0), then the left leaf pair (-1), then the right (+1). */
    static int side(int part) {
        return part < 2 ? 0 : part < 4 ? -1 : 1;
    }

    /** Forces the models to be requested, before Polymer builds the pack. */
    public static void bootstrap() {
        Models.PARTS.size();
    }

    static ItemStack part(String trim, int part) {
        PolymerModelData[] set = Models.PARTS.getOrDefault(trim, Models.PARTS.get("neutral"));
        return paper(set[part]);
    }

    /** @param side -1 the left leaf's half, +1 the right's */
    static ItemStack icon(RouteMap.Stop stop, int side) {
        return paper(Models.ICONS.get(stop)[side < 0 ? 0 : 1]);
    }

    private static ItemStack paper(PolymerModelData model) {
        ItemStack stack = new ItemStack(Items.PAPER);
        stack.set(DataComponents.CUSTOM_MODEL_DATA, new CustomModelData(model.value()));
        return stack;
    }

    /** Requested when first touched, so a classpath without Polymer (a unit test) never loads it. */
    private static final class Models {
        static final Map<String, PolymerModelData[]> PARTS = new HashMap<>();
        static final Map<RouteMap.Stop, PolymerModelData[]> ICONS = new HashMap<>();

        static {
            for (String trim : TRIMS) {
                PolymerModelData[] set = new PolymerModelData[SealDoorModels.PARTS.length];
                for (int i = 0; i < set.length; i++) set[i] = request("gate_door/" + trim + "/" + SealDoorModels.PARTS[i]);
                PARTS.put(trim, set);
            }
            for (RouteMap.Stop stop : RouteMap.Stop.values()) {
                String name = stop.name().toLowerCase(Locale.ROOT);
                ICONS.put(stop, new PolymerModelData[] {request("gate_door/icon/" + name + "_left"), request("gate_door/icon/" + name + "_right")});
            }
        }

        private static PolymerModelData request(String path) {
            return PolymerResourcePackUtils.requestModel(Items.PAPER, ResourceLocation.fromNamespaceAndPath("cobbletowers", path));
        }
    }
}
